#!/usr/bin/env node
/**
 * Writes docs/demo/agent-session.md: the tool calls an agent makes when it follows the hexvero
 * skill on the example app, with the real results it receives (trimmed for reading, never
 * edited). The calls are scripted, not chosen by a model; the point is what the agent sees.
 *
 *   npm run build && node scripts/demo-agent.mjs
 */
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const client = new Client({ name: "demo-agent", version: "1" });
await client.connect(
  new StdioClientTransport({
    command: process.execPath,
    args: [join(root, "packages", "cli", "bin", "hexvero.js"), "mcp"],
  }),
);
const out = [];
const show = (value, keep) => {
  const json = JSON.stringify(value, null, 2);
  const lines = json.split("\n");
  return lines.length <= keep
    ? json
    : `${lines.slice(0, keep).join("\n")}\n  … (${lines.length - keep} more lines)`;
};
const step = async (why, name, args, keep = 30, pick = (x) => x) => {
  const result = await client.callTool({ name, arguments: args });
  const text = result.content.map((c) => c.text ?? "").join("");
  const body = JSON.parse(text);
  out.push(
    `### ${why}\n\n\`${name}\` ${JSON.stringify(args).replace(root, "<repo>")}\n\n\`\`\`json\n${show(pick(body), keep).replaceAll(root, "<repo>")}\n\`\`\`\n\n_${Buffer.byteLength(text)} bytes received._\n`,
  );
  return body;
};

const question =
  "Which IPC channels can the renderer of notesdesk 1.4.0 reach, is nodeIntegration on, and what changed in 1.5.0?";
const v14 = join(root, "examples", "notesdesk-1.4.0.asar");
const v15 = join(root, "examples", "notesdesk-1.5.0.asar");
const a = (await step("Open the target", "hexvero_open", { path: v14 }, 12)).id;
const analysis = await step(
  "Read the first answer: summary, findings, limitations, next calls",
  "hexvero_analyze",
  { targetId: a },
  60,
  (x) => ({
    summary: x.summary,
    complete: x.complete,
    findings: x.findings,
    limitations: x.limitations,
    next: x.next,
  }),
);
await step(
  "Follow the first suggestion: the channels with senders and receivers",
  analysis.next[0].tool,
  analysis.next[0].args,
  40,
);
await step(
  "Corroborate: the call sites of the one channel that opens things",
  "hexvero_collection",
  { targetId: a, collection: "ipc", text: "shell:open" },
  30,
);
const b = (await step("Open the newer build", "hexvero_open", { path: v15 }, 12)).id;
await step(
  "Compare the window settings",
  "hexvero_compare",
  { targetA: a, targetB: b, collection: "webPreferences" },
  40,
  (x) => ({
    key: x.key,
    complete: x.complete,
    added: x.added,
    removed: x.removed,
    changed: x.changed,
  }),
);
await step(
  "Compare the channels",
  "hexvero_compare",
  { targetA: a, targetB: b, collection: "ipcChannels" },
  30,
  (x) => ({
    key: x.key,
    complete: x.complete,
    added: x.added,
    removed: x.removed,
    changed: x.changed,
  }),
);
await client.close();

writeFileSync(
  join(root, "docs", "demo", "agent-session.md"),
  `# An agent investigation, call by call

Generated by \`node scripts/demo-agent.mjs\` against the built MCP server. The calls follow the
[hexvero skill](../../skills/hexvero/SKILL.md) on the example app in \`examples/\`; they are
scripted, not chosen by a model, so this shows what an agent receives, not how well a particular
model reasons. Results are real and only shortened where marked.

**Question:** ${question}

${out.join("\n")}
## An answer the evidence supports

- The renderer can reach six channels, all handled in main.js: app:quit, notes:list, notes:save, settings:get, settings:set and shell:open (\`ipcChannels\`).
- \`shell:open\` is sent from preload.js line 9 and handled in main.js line 30 (\`ipc\`).
- 1.4.0 writes \`nodeIntegration: true\` and \`sandbox: false\` for its window (main.js:14 and :15, findings). This is a setting in the code, not observed behaviour.
- 1.5.0 turns both off and replaces \`shell:open\` with \`update:check\` (\`compare\` on \`webPreferences\` and \`ipcChannels\`, both complete).
- Not established: whether web content in 1.4.0 can actually inject script; that needs more than static reading.
`,
);
console.log("wrote docs/demo/agent-session.md");
