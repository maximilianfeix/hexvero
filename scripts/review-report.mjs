#!/usr/bin/env node
/**
 * Runs the quality gates (typecheck, lint, format, tests, duplicate-export scan)
 * and renders one Markdown report. Exit code 1 when any gate fails.
 * Used by the review workflow to post a single threaded PR comment.
 */
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const gates = [
  {
    name: "Typecheck",
    command: "npm",
    args: ["run", "-s", "typecheck"],
    hint: "Fix the TypeScript errors listed above; `exactOptionalPropertyTypes` is on.",
  },
  {
    name: "Lint",
    command: "npx",
    args: ["oxlint", "packages", "--deny-warnings"],
    hint: "Run `npm run lint` locally; warnings are errors here.",
  },
  {
    name: "Format",
    command: "npx",
    args: ["oxfmt", "--check", "."],
    hint: "Run `npm run format` and commit.",
  },
  {
    name: "Tests",
    command: "npx",
    args: ["vitest", "run", "--reporter=dot"],
    hint: "Run `npm test`; every parser PR needs fixture coverage.",
  },
  {
    name: "Code shape",
    command: "node",
    args: ["scripts/check-shape.mjs"],
    hint: "See the findings above; each is a project rule from CONTRIBUTING.md.",
  },
];

const results = [];
for (const gate of gates) {
  const started = Date.now();
  const run = spawnSync(gate.command, gate.args, {
    encoding: "utf8",
    env: { ...process.env, FORCE_COLOR: "0", NO_COLOR: "1" },
  });
  const output = `${run.stdout ?? ""}${run.stderr ?? ""}`.trim();
  results.push({
    ...gate,
    ok: run.status === 0,
    output,
    ms: Date.now() - started,
  });
}

const ok = results.every((r) => r.ok);
const lines = [];
lines.push(
  `## hexvero review · ${
    ok ? "all gates green" : `${results.filter((r) => !r.ok).length} gate(s) failing`
  }`,
);
lines.push("");
lines.push("| Gate | Result | Time |");
lines.push("| --- | --- | --- |");
for (const r of results)
  lines.push(`| ${r.name} | ${r.ok ? "✅ pass" : "❌ fail"} | ${(r.ms / 1000).toFixed(1)} s |`);
for (const r of results.filter((x) => !x.ok)) {
  lines.push(
    "",
    `<details><summary><b>${r.name}</b> — ${r.hint}</summary>`,
    "",
    "```text",
    trim(r.output, 6000),
    "```",
    "",
    "</details>",
  );
}
const shape = results.find((r) => r.name === "Code shape");
if (shape?.ok && shape.output)
  lines.push(
    "",
    "<details><summary>Code shape notes</summary>",
    "",
    "```text",
    trim(shape.output, 3000),
    "```",
    "",
    "</details>",
  );
lines.push(
  "",
  `<sub>Generated by \`scripts/review-report.mjs\` on ${new Date().toISOString()} · commit ${process.env.GITHUB_SHA?.slice(0, 7) ?? "local"}</sub>`,
);

const report = lines.join("\n");
writeFileSync(process.env.REVIEW_REPORT_PATH ?? "review-report.md", report);
console.log(report);
process.exit(ok ? 0 : 1);

function trim(text, max) {
  return text.length > max
    ? `${text.slice(0, max)}\n… (${text.length - max} more characters)`
    : text;
}
